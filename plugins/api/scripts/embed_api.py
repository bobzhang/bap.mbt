#!/usr/bin/env python3
"""Embeds the API specification files from `plugins/api/api/` into
`plugins/api/bundled_api.mbt` as MoonBit string constants.

Usage:
    python3 plugins/api/scripts/embed_api.py [--copy UPSTREAM_BAP_ROOT]

With `--copy`, the upstream API files are first copied from the BAP
source tree (`plugins/api/api/<lang>/*.h`) into `plugins/api/api/`.
"""

import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
API = os.path.join(PKG, "api")
LANGS = ["c"]


def copy(upstream):
    for lang in LANGS:
        srcdir = os.path.join(upstream, "plugins/api/api", lang)
        dstdir = os.path.join(API, lang)
        os.makedirs(dstdir, exist_ok=True)
        for name in sorted(os.listdir(srcdir)):
            if name.endswith(".h"):
                shutil.copyfile(os.path.join(srcdir, name),
                                os.path.join(dstdir, name))


def embed():
    out = []
    out.append("// Generated by plugins/api/scripts/embed_api.py, DO NOT EDIT.\n")
    out.append("// The API specification files bundled with upstream BAP.\n")
    out.append("\n///|\n")
    out.append("/// The bundled API files as `(path, contents)` pairs, where `path` is\n")
    out.append("/// `<language>/<name>`, e.g., `\"c/posix.h\"`.\n")
    out.append("pub fn bundled_api_files() -> Array[(String, String)] {\n")
    out.append("  [\n")
    for lang in LANGS:
        d = os.path.join(API, lang)
        for name in sorted(os.listdir(d)):
            if not name.endswith(".h"):
                continue
            with open(os.path.join(d, name), encoding="utf-8") as f:
                text = f.read()
            out.append("    (\n")
            out.append('      "%s/%s",\n' % (lang, name))
            lines = text.split("\n")
            trailing = bool(lines) and lines[-1] == ""
            if trailing:
                lines = lines[:-1]
            if not lines:
                out.append('      "",\n')
            else:
                out.append("      (\n")
                for line in lines:
                    line = line.replace("\r", "").replace("\t", "        ")
                    out.append("        #|%s\n" % line)
                if trailing:
                    out.append("        #|\n")
                out.append("      ),\n")
            out.append("    ),\n")
    out.append("  ]\n")
    out.append("}\n")
    with open(os.path.join(PKG, "bundled_api.mbt"), "w", encoding="utf-8") as f:
        f.write("".join(out))


def main(argv):
    if len(argv) == 3 and argv[1] == "--copy":
        copy(argv[2])
    elif len(argv) != 1:
        print(__doc__)
        return 1
    embed()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
