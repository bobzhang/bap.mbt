#!/usr/bin/env python3
"""Embeds the Primus Lisp sources from `primus_lisp/lisp/` into
`primus_lisp/lisp_library.mbt` as MoonBit string constants.

Usage:
    python3 primus_lisp/scripts/embed_lisp.py [--copy UPSTREAM_BAP_ROOT]

With `--copy`, the upstream `.lisp` files are first copied from the BAP
source tree (plugins/primus_lisp/{lisp,site-lisp,semantics},
plugins/{riscv,arm,powerpc,x86}/semantics) into `primus_lisp/lisp/`.
"""

import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
LISP = os.path.join(PKG, "lisp")

LAYOUT = [
    ("lisp", "plugins/primus_lisp/lisp"),
    ("site-lisp", "plugins/primus_lisp/site-lisp"),
    ("semantics/primus", "plugins/primus_lisp/semantics"),
    ("semantics/riscv", "plugins/riscv/semantics"),
    ("semantics/arm", "plugins/arm/semantics"),
    ("semantics/powerpc", "plugins/powerpc/semantics"),
    ("semantics/x86", "plugins/x86/semantics"),
    ("taint", "plugins/primus_taint/lisp"),
    ("constant-tracker", "plugins/constant_tracker/lisp"),
    ("primus-test", "plugins/primus_test/lisp"),
    ("approximation", "plugins/primus_approximation/lisp"),
]


def copy(upstream):
    for dst, src in LAYOUT:
        srcdir = os.path.join(upstream, src)
        dstdir = os.path.join(LISP, dst)
        os.makedirs(dstdir, exist_ok=True)
        for name in sorted(os.listdir(srcdir)):
            if name.endswith(".lisp"):
                shutil.copyfile(os.path.join(srcdir, name),
                                os.path.join(dstdir, name))


def embed():
    out = []
    out.append("// Generated by primus_lisp/scripts/embed_lisp.py, DO NOT EDIT.\n")
    out.append("// The upstream Primus Lisp sources (library and semantics).\n")
    entries = []
    for dst, _ in LAYOUT:
        d = os.path.join(LISP, dst)
        for name in sorted(os.listdir(d)):
            if name.endswith(".lisp"):
                entries.append((dst + "/" + name, os.path.join(d, name)))
    out.append("\n///|\n")
    out.append("/// All embedded upstream Lisp files as `(path, contents)` pairs,\n")
    out.append("/// where `path` is relative to the embedded library root, e.g.,\n")
    out.append("/// `\"lisp/init.lisp\"` or `\"semantics/riscv/riscv.lisp\"`.\n")
    out.append("pub fn embedded_lisp_files() -> Array[(String, String)] {\n")
    out.append("  [\n")
    for path, full in entries:
        with open(full, encoding="utf-8") as f:
            text = f.read()
        out.append("    (\n")
        out.append('      "%s",\n' % path)
        lines = text.split("\n")
        if lines and lines[-1] == "":
            lines = lines[:-1]
            trailing = True
        else:
            trailing = False
        if not lines:
            out.append('      "",\n')
        else:
            out.append("      (\n")
            for line in lines:
                line = line.replace("\r", "").replace("\t", "        ")
                out.append("        #|%s\n" % line)
            if trailing:
                out.append("        #|\n")
            out.append("      ),\n")
        out.append("    ),\n")
    out.append("  ]\n")
    out.append("}\n")
    with open(os.path.join(PKG, "lisp_library.mbt"), "w", encoding="utf-8") as f:
        f.write("".join(out))
    print("embedded %d files" % len(entries))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--copy":
        copy(sys.argv[2])
    embed()
